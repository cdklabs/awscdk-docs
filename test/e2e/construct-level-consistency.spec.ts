import { expect, test, type Page } from '@playwright/test';
import {
  CFN_QUEUE_PAGE,
  IQUEUE_PAGE,
  QUEUE_ENCRYPTION_PAGE,
  QUEUE_GRANTS_PAGE,
  QUEUE_PAGE,
  QUEUE_PROPS_PAGE,
} from './fixture.js';

// One construct level, three surfaces. The level is a single determination —
// `constructLevel()` — but it reaches the reader through three separately
// assembled labels: the page badge, a link's hover preview, and the sidebar
// entry, each with its own text and color. Nothing here can be checked
// from the generator or the stylesheet alone: the label is assembled in three
// places and the colors only exist once the cascade has run, so this spec
// reads all three surfaces in a browser and compares them to each other
// rather than to a hard-coded expectation.
//
// Fixture note: aws-sqs gives an L2 (`Queue`) and an L1 (`CfnQueue`) that
// live in the same sidebar section, so one page shows both. There is no L3
// construct in the fixture; L3 is pinned at the docgen layer in
// `test/construct-pages.test.ts` and for contrast in `test/theme.test.ts`.
test.describe('construct level is consistent across its three surfaces', () => {
  const SIDEBAR_LINK = '.api-sidebar a.api-sidebar-link';

  /** Resolve once no scroll event has fired anywhere on the page for `quiet` ms. */
  async function scrollSettled(page: Page, quiet = 300): Promise<void> {
    await page.evaluate(async (quietMs) => {
      await new Promise<void>((resolve) => {
        const done = () => {
          window.removeEventListener('scroll', bump, true);
          resolve();
        };
        let timer = setTimeout(done, quietMs);
        function bump() {
          clearTimeout(timer);
          timer = setTimeout(done, quietMs);
        }
        window.addEventListener('scroll', bump, { capture: true, passive: true });
      });
    }, quiet);
  }

  /** Both queue constructs are deep in the tree; the filter surfaces them. */
  async function surfaceQueues(page: Page) {
    await expect(page.locator('.api-sidebar-nav')).toBeVisible();
    await page
      .getByRole('textbox', { name: 'Filter API symbols in the sidebar' })
      .fill('Queue');
    await expect(page.locator(`${SIDEBAR_LINK}[href$=".aws_sqs.Queue"]`)).toBeVisible();
    await expect(page.locator(`${SIDEBAR_LINK}[href$=".aws_sqs.CfnQueue"]`)).toBeVisible();
  }

  /** Computed foreground and background, as one comparable string. */
  const PAINT = (el: Element) => {
    const style = getComputedStyle(el);
    return `${style.color}|${style.backgroundColor}`;
  };

  async function h1Badge(page: Page): Promise<{ text: string; paint: string }> {
    const badge = page.locator('h1 .VPBadge');
    await expect(badge).toBeVisible();
    return { text: (await badge.innerText()).trim(), paint: await badge.evaluate(PAINT) };
  }

  /**
   * Hover the sidebar's link to another type and read its preview chip.
   *
   * A scroll of the hovered link's own scroller cancels the pending preview,
   * so nothing may scroll between the hover and the summary fetch resolving.
   * The sidebar's jump-to-current animation is still running when the rows
   * appear, and it would move the row out of view again after an early
   * `scrollIntoViewIfNeeded()` — leaving `hover()` to re-scroll. So: let the
   * animation finish, bring the row into view, let that settle, then hover.
   * A real reader scrolls, stops, then hovers.
   */
  async function previewChip(
    page: Page,
    fqnSuffix: string,
  ): Promise<{ text: string; paint: string }> {
    const link = page.locator(`${SIDEBAR_LINK}[href$="${fqnSuffix}"]`);
    await scrollSettled(page);
    await link.scrollIntoViewIfNeeded();
    await scrollSettled(page);
    await link.hover();

    const tooltip = page.locator('#api-type-tooltip');
    // The first hover of the session fetches and parses the whole summary
    // map, so this one assertion gets a longer budget than the default.
    await expect(tooltip).toHaveAttribute('aria-hidden', 'false', { timeout: 15_000 });
    const chip = tooltip.locator('.type-tooltip-kind');
    await expect(chip).toBeVisible();
    return { text: (await chip.innerText()).trim(), paint: await chip.evaluate(PAINT) };
  }

  /** The sidebar tag on a RESTING row: the active row follows the accent. */
  async function sidebarTag(
    page: Page,
    fqnSuffix: string,
  ): Promise<{ text: string; color: string }> {
    const row = page.locator(`${SIDEBAR_LINK}[href$="${fqnSuffix}"]`);
    await expect(row).not.toHaveClass(/active/);
    const tag = row.locator('.api-sidebar-level');
    await expect(tag).toBeVisible();
    // The glyph is generated by the stylesheet from `data-level`, so read
    // what is painted rather than `innerText`, which is empty by design.
    return {
      text: await tag.evaluate((el) =>
        getComputedStyle(el, '::before').content.replace(/^"|"$/g, ''),
      ),
      color: await tag.evaluate((el) => getComputedStyle(el).color),
    };
  }

  test('the page badge and a link preview of the same type read identically', async ({ page }) => {
    // The preview is read from the OTHER page, because a link to the page
    // you are on gets no preview at all — so this compares two surfaces
    // built by two different code paths for the same type.
    await page.goto(QUEUE_PAGE);
    const queueBadge = await h1Badge(page);

    await page.goto(CFN_QUEUE_PAGE);
    await surfaceQueues(page);
    const queuePreview = await previewChip(page, '.aws_sqs.Queue');

    expect(queueBadge.text).toBe('L2 construct');
    // Byte-identical, not merely "both mention L2": the divergence this
    // issue reports was `L2 construct` against `Construct (L2)`.
    expect(queuePreview.text).toBe(queueBadge.text);
    // And the same palette triple, so the preview of a link is recognizably
    // the page it points at.
    expect(queuePreview.paint).toBe(queueBadge.paint);
  });

  test('the same holds for an L1, in the L1 palette', async ({ page }) => {
    await page.goto(CFN_QUEUE_PAGE);
    const cfnBadge = await h1Badge(page);

    await page.goto(QUEUE_PAGE);
    await surfaceQueues(page);
    const cfnPreview = await previewChip(page, '.aws_sqs.CfnQueue');

    expect(cfnBadge.text).toBe('L1 construct');
    expect(cfnPreview.text).toBe(cfnBadge.text);
    expect(cfnPreview.paint).toBe(cfnBadge.paint);
  });

  test('the sidebar tag carries the level in the page badge\'s own hue', async ({ page }) => {
    // The visible tag stays the bare level — that is the sidebar-navigation ADR's
    // decision and this spec must not reverse it — but its foreground now
    // comes from the same triple, so the short tag and the long badge are
    // visibly the same fact.
    await page.goto(QUEUE_PAGE);
    const queueBadge = await h1Badge(page);
    const badgeColor = queueBadge.paint.split('|')[0];

    await page.goto(CFN_QUEUE_PAGE);
    await surfaceQueues(page);
    const queueTag = await sidebarTag(page, '.aws_sqs.Queue');

    expect(queueTag.text).toBe('L2');
    expect(queueTag.color).toBe(badgeColor);
  });

  test('the active row keeps the accent, so row state still outranks level', async ({ page }) => {
    // The level hues are the one new thing that could beat row state. On the
    // Queue page the Queue row is active for real, and its tag must read as
    // the accent rather than as L2 — otherwise a reader loses "you are here"
    // to a color that only repeats what the name already says.
    await page.goto(QUEUE_PAGE);
    const badge = await h1Badge(page);
    const l2Hue = badge.paint.split('|')[0];
    await surfaceQueues(page);

    const activeRow = page.locator(`${SIDEBAR_LINK}[href$=".aws_sqs.Queue"]`);
    await expect(activeRow).toHaveClass(/active/);
    const activeColor = await activeRow
      .locator('.api-sidebar-level')
      .evaluate((el) => getComputedStyle(el).color);

    // Resolve the accent through a probe rather than hard-coding a hex, so
    // this keeps holding if the brand ramp is retuned.
    const accent = await page.evaluate(() => {
      const probe = document.createElement('span');
      probe.style.color = 'var(--vp-c-brand-2)';
      document.body.append(probe);
      const value = getComputedStyle(probe).color;
      probe.remove();
      return value;
    });

    expect(activeColor).toBe(accent);
    expect(activeColor).not.toBe(l2Hue);
  });

  test('L1 and L2 differ from each other on all three surfaces', async ({ page }) => {
    // Agreement across surfaces is worthless if every level looks the same:
    // this is the half of the contract that catches a palette collapsed back
    // to one hue.
    await page.goto(QUEUE_PAGE);
    const l2Badge = await h1Badge(page);
    await surfaceQueues(page);
    const l1Tag = await sidebarTag(page, '.aws_sqs.CfnQueue');
    const l1Preview = await previewChip(page, '.aws_sqs.CfnQueue');

    await page.goto(CFN_QUEUE_PAGE);
    const l1Badge = await h1Badge(page);
    await surfaceQueues(page);
    const l2Tag = await sidebarTag(page, '.aws_sqs.Queue');
    const l2Preview = await previewChip(page, '.aws_sqs.Queue');

    expect(l1Badge.paint).not.toBe(l2Badge.paint);
    expect(l1Preview.paint).not.toBe(l2Preview.paint);
    expect(l1Tag.color).not.toBe(l2Tag.color);
    expect(l1Preview.text).not.toBe(l2Preview.text);
  });

  for (const appearance of ['light', 'dark'] as const) {
    test(`non-level kinds match their page badges in ${appearance} mode`, async ({ page }) => {
      await page.addInitScript((theme) => {
        window.localStorage.setItem('vitepress-theme-appearance', theme);
      }, appearance);

      const examples = [
        { name: 'QueueEncryption', suffix: '.aws_sqs.QueueEncryption', page: QUEUE_ENCRYPTION_PAGE },
        { name: 'QueueProps', suffix: '.aws_sqs.QueueProps', page: QUEUE_PROPS_PAGE },
        { name: 'IQueue', suffix: '.aws_sqs.IQueue', page: IQUEUE_PAGE },
        { name: 'QueueGrants', suffix: '.aws_sqs.QueueGrants', page: QUEUE_GRANTS_PAGE },
      ];

      for (const example of examples) {
        await page.goto(example.page);
        const badge = await h1Badge(page);

        await page.goto(QUEUE_PAGE);
        await page
          .getByRole('textbox', { name: 'Filter API symbols in the sidebar' })
          .fill(example.name);
        await expect(page.locator(`${SIDEBAR_LINK}[href$="${example.suffix}"]`)).toBeVisible();
        const preview = await previewChip(page, example.suffix);

        expect(preview.text).toBe(badge.text);
        expect(preview.paint).toBe(badge.paint);
      }
    });
  }
});
