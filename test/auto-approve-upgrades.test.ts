import { readFileSync } from 'fs';
import { join } from 'path';

/**
 * projen's recurring upgrade-main deps PR
 * carries the 'auto-approve' label from creation via the built-in
 * `depsUpgradeOptions.workflowOptions.labels` option, matching the label's
 * existing trust boundary for the AutoApprove mechanism.
 */
const workflowPath = join(import.meta.dirname, '..', '.github', 'workflows', 'upgrade-main.yml');

describe('upgrade-main workflow', () => {
  const content = readFileSync(workflowPath, 'utf-8');

  test('is generated by projen', () => {
    expect(content).toContain('Generated by projen');
  });

  test('labels the deps-upgrade PR auto-approve at creation', () => {
    expect(content).toContain('labels: auto-approve');
  });
});
