describe('Combined deploy + release workflow', () => {
  // Config shape throughout this block: every effect this workflow has lands
  // on S3 or on a git tag.
  const workflowPath = resolve(ROOT, '.github/workflows/deploy-and-release.yml');

  test('combined workflow exists and is projen-managed', () => {
    expect(existsSync(workflowPath)).toBe(true);
    const content = readFileSync(workflowPath, 'utf-8');
    expect(content).toContain('Generated by projen');
  });

  // A file that must not exist has no output at all, deployed or otherwise.
  test('old separate deploy and release workflows are removed', () => {
    expect(existsSync(resolve(ROOT, '.github/workflows/deploy.yml'))).toBe(false);
    expect(existsSync(resolve(ROOT, '.github/workflows/release.yml'))).toBe(false);
  });

  test('workflow builds docs via projen', () => {
    const content = readFileSync(workflowPath, 'utf-8');
    expect(content).toContain('npx projen docs:build');
  });

  test('workflow packages VitePress dist', () => {
    const content = readFileSync(workflowPath, 'utf-8');
    expect(content).toContain('docs/.vitepress/dist');
  });

  test('workflow does not deploy to GitHub Pages', () => {
    const content = readFileSync(workflowPath, 'utf-8');
    expect(content).not.toContain('actions/deploy-pages');
    expect(content).not.toContain('actions/upload-pages-artifact');
    expect(content).not.toContain('github-pages');
    expect(content).not.toMatch(/\n {6}pages: write\n/);
  });

  test('workflow triggers on push to main, PRs, and manual dispatch', () => {
    const content = readFileSync(workflowPath, 'utf-8');
    expect(content).toContain('- main');
    expect(content).toContain('pull_request:');
    expect(content).toContain('workflow_dispatch:');
  });

  // Config shape: the job graph only plays out in a CI run.
  const jobOf = (name: string) => {
    const content = readFileSync(workflowPath, 'utf-8');
    const start = content.indexOf(`\n  ${name}:\n`);
    expect(start).toBeGreaterThan(-1);
    const rest = content.slice(start + 1);
    const next = rest.slice(1).search(/\n {2}[A-Za-z0-9_-]+:\n/);
    return `${next === -1 ? rest : rest.slice(0, next + 1)}\n`;
  };
  const needsOf = (job: string) => {
    const block = jobOf(job);
    const list = block.match(/\n {4}needs:\n((?: {6}- .+\n)+)/)?.[1];
    if (list) return list.trim().split('\n').map((l) => l.trim().replace(/^- /, '')).sort();
    const scalar = block.match(/\n {4}needs: (.+)\n/)?.[1];
    return scalar ? [scalar] : [];
  };
  const ifOf = (job: string) => jobOf(job).match(/\n {4}if: "?(.+?)"?\n/)?.[1];

  test('release runs on main alongside the build, needing nothing from it', () => {
    expect(needsOf('release')).toEqual([]);
    expect(ifOf('release')).toBe("github.ref == 'refs/heads/main'");
  });

  test('the publish job needs the built site and the release, and skips tagged versions, dry runs and non-main refs', () => {
    const job = 'release_docs_awscdk-docs';
    expect(needsOf(job)).toEqual(['build', 'release']);
    const cond = ifOf(job)!;
    expect(cond).toContain("needs.release.outputs.tag_exists != 'true'");
    expect(cond).toContain("github.ref == 'refs/heads/main'");
    expect(cond).toContain('!inputs.dry_run');
  });

  test('the GitHub release, which creates the tag, waits for the publish job', () => {
    expect(needsOf('release_github')).toEqual(['release', 'release_docs_awscdk-docs']);
    const cond = ifOf('release_github')!;
    // Skipped publish jobs (a dry run) must not skip it, a failed one must.
    expect(cond).toContain('!cancelled() && !failure()');
    expect(cond).toContain("needs.release.result == 'success'");
    expect(cond).toContain("needs.release.outputs.tag_exists != 'true'");
  });

  test('dry-run support is preserved', () => {
    const content = readFileSync(workflowPath, 'utf-8');
    expect(content).toContain('dry_run:');
    expect(jobOf('release_github')).toMatch(/- name: Release\n\s+id: release\n\s+if: \$\{\{ !inputs\.dry_run \}\}\n/);
  });

  test('release preserves conventional changelog and GitHub Releases publishing', () => {
    const content = readFileSync(workflowPath, 'utf-8');
    expect(content).toContain('npx projen release');
    expect(content).toContain('gh release create');
    expect(content).toContain('dist/changelog.md');
  });
});
describe('single build job', () => {
  // Config shape: which runner a job lands on and how jobs depend on each other have no output outside a CI run.
  const workflowPath = resolve(ROOT, '.github/workflows/deploy-and-release.yml');
  const content = readFileSync(workflowPath, 'utf-8');
  const jobBlock = (name: string) => {
    const start = content.indexOf(`\n  ${name}:\n`);
    expect(start).toBeGreaterThan(-1);
    const rest = content.slice(start + 1);
    const next = rest.slice(1).search(/\n {2}[A-Za-z0-9_-]+:\n/);
    return next === -1 ? rest : rest.slice(0, next + 1);
  };

  test('build runs on an ephemeral CodeBuild runner unique to the run attempt', () => {
    expect(jobBlock('build')).toContain(
      'runs-on: codebuild-awscdk-docs-github-actions-runner-${{ github.run_id }}-${{ github.run_attempt }}\n',
    );
  });

  test('build is one job that builds every shard itself', () => {
    const build = jobBlock('build');
    expect(build).not.toContain('matrix:');
    expect(build).not.toContain('needs:');
    expect(build).toMatch(/npx projen docs:build:sharded -- --num-shards \d+ --heap \d+ --concurrency \d+\n/);
    expect(content).not.toContain('\n  build_shards:\n');
    expect(content).not.toContain('\n  merge:\n');
  });

  // Config shape: which steps run on which refs only shows in a CI run.
  test('every build packages and uploads the site zip', () => {
    const build = jobBlock('build');
    // A step runs from its `- ` line to the next step at any depth.
    const step = (marker: string) => {
      const at = build.indexOf(marker);
      expect(at).toBeGreaterThan(-1);
      const start = build.lastIndexOf('- ', at);
      const end = build.slice(at).search(/\n {6,}- /);
      return build.slice(start, end === -1 ? undefined : at + end);
    };
    expect(step('name: Package docs site for S3 publishing')).not.toContain('if:');
    expect(step('name: Upload docs site zip')).not.toContain('if:');
  });

  test('build only reads repository contents', () => {
    expect(jobBlock('build')).toMatch(/\n {4}permissions:\n {6}contents: read\n {4}steps:\n/);
  });

  // Config shape: a status check's name only exists in GitHub's checks list.
  test('build reports as build-docs, a check name no other PR job reports', () => {
    expect(jobBlock('build')).toContain('\n    name: build-docs\n');
    const dir = resolve(ROOT, '.github/workflows');
    const checks = readdirSync(dir)
      .map((file) => readFileSync(resolve(dir, file), 'utf-8'))
      .filter((workflow) => /\non:\n(?: {2}.*\n)*? {2}pull_request:/.test(workflow))
      .flatMap((workflow) => {
        const jobs = workflow.slice(workflow.indexOf('\njobs:\n') + 7).split(/^(?= {2}[A-Za-z0-9_-]+:$)/m);
        return jobs.map((job) => job.match(/^ {4}name: (.+)$/m)?.[1] ?? job.match(/^ {2}(\S+):$/m)![1]);
      });
    expect(checks).toContain('build');
    expect(checks).toContain('build-docs');
    expect(checks.length).toBe(new Set(checks).size);
  });
});


